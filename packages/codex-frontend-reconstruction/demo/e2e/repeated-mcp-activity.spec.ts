import {test,expect} from "@playwright/test";

test("source Je/bg opens only the eligible consecutive MCP calls and keeps the barrier separate",async ({page},testInfo)=>{
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  await page.goto("/");
  await page.getByRole("button",{name:/工具调用与审批交互/}).click();
  const turn=page.locator('[data-demo-turn-id="review-repeated-mcp"]');
  await expect(turn).toBeVisible();
  const outer=turn.locator("[data-recovered-agent-activity]");
  await outer.locator(".codex-agent-activity__toggle").click();
  const group=turn.locator("[data-codex-activity-group]");
  await expect(group).toBeVisible();
  await group.locator(".codex-activity-group-row__toggle").click();
  const repeated=group.locator('[data-codex-source-repeated-group="mcp-tool-call"]');
  await expect(repeated).toHaveCount(2);
  await expect(repeated.first()).toHaveAttribute("data-codex-source-repeated-header-variant","mcp-tool");
  await expect(repeated.nth(1)).toHaveAttribute("data-codex-source-repeated-header-variant","codex-action");
  await expect(repeated.nth(1).locator("summary")).toContainText("已搜索文件 · 2 次调用");
  await expect(repeated.locator("[data-demo-repeated-mcp-icon]")).toHaveCount(2);
  await expect(repeated.first().locator("summary")).toContainText("search · 2 次调用");
  await expect(repeated.first().locator("[data-codex-source-repeated-body]")).toBeHidden();
  await repeated.first().locator("summary").click();
  await expect(repeated.first().locator("[data-codex-source-repeated-body]")).toBeVisible();
  await expect(repeated.first().locator(".codex-activity-group-row__subrow")).toHaveCount(2);
  await expect(group.locator(".codex-activity-group-row__subrow")).toHaveCount(5);
  await expect(group.locator('[data-codex-source-repeated-group="external-event"]')).toHaveCount(0);
  await repeated.first().locator("summary").click();
  await expect(repeated.first().locator("[data-codex-source-repeated-body]")).toBeHidden();
  await repeated.nth(1).locator("summary").click();
  await expect(repeated.nth(1).locator("[data-codex-source-repeated-body]")).toBeVisible();
  await repeated.nth(1).scrollIntoViewIfNeeded();
  await page.screenshot({path:testInfo.outputPath("codex-repeated-mcp-headers.png"),animations:"disabled"});
  expect(errors).toEqual([]);
});
